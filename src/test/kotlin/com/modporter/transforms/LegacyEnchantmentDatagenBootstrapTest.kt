import kotlin.io.path.exists
import kotlin.io.path.readText
import kotlin.io.path.writeText
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

class LegacyEnchantmentDatagenBootstrapTest {
    @TempDir
    lateinit var directory: Path

    @Test
    fun `derived enchantments and their vanilla tags are generated by the project datagen`() {
        writeProject()
        val before = snapshot()

        assertEquals(4, migrate(dryRun = true).size)
        assertEquals(before, snapshot())
        assertFalse(directory.resolve("src/main/java/example/data/ModPorterEnchantmentTagsProvider.java").exists())

        val changes = migrate(dryRun = false)
        assertEquals(4, changes.size)
        assertTrue(changes.all { it.ruleId == LegacyEnchantmentDatagenBootstrap.RULE_ID })

        val enchantments = read("example/registry/ModEnchantments.java")
        val compact = compact(enchantments)
        assertTrue(
            compact.contains(
                "public static void bootstrap(net.minecraft.data.worldgen.BootstrapContext" +
                    "<net.minecraft.world.item.enchantment.Enchantment> context) {"
            ),
            enchantments
        )
        assertTrue(
            compact.contains(
                "context.register(REACH, net.minecraft.world.item.enchantment.Enchantment.enchantment(" +
                    "net.minecraft.world.item.enchantment.Enchantment.definition(" +
                    "net.minecraft.core.HolderSet.direct(" +
                    "items.getOrThrow(net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ITEM, " +
                    "net.minecraft.resources.ResourceLocation.parse(\"example:long_arm\"))), " +
                    "items.getOrThrow(net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ITEM, " +
                    "net.minecraft.resources.ResourceLocation.parse(\"example:longer_arm\")))), " +
                    "2, 2, net.minecraft.world.item.enchantment.Enchantment.dynamicCost(1, 10), " +
                    "net.minecraft.world.item.enchantment.Enchantment.dynamicCost(21, 10), 4, " +
                    "net.minecraft.world.entity.EquipmentSlotGroup.MAINHAND)) .build(REACH.location()));"
            ),
            enchantments
        )
        val chestArmor = "items.getOrThrow(net.minecraft.tags.TagKey.create(net.minecraft.core.registries.Registries.ITEM, " +
            "net.minecraft.resources.ResourceLocation.parse(\"minecraft:enchantable/chest_armor\")))"
        assertTrue(
            compact.contains(
                "context.register(HEX, net.minecraft.world.item.enchantment.Enchantment.enchantment(" +
                    "net.minecraft.world.item.enchantment.Enchantment.definition($chestArmor, $chestArmor, " +
                    "1, 1, net.minecraft.world.item.enchantment.Enchantment.dynamicCost(25, 0), " +
                    "net.minecraft.world.item.enchantment.Enchantment.dynamicCost(50, 0), 8, " +
                    "net.minecraft.world.entity.EquipmentSlotGroup.CHEST)) " +
                    ".exclusiveWith(net.minecraft.core.HolderSet.direct(" +
                    "enchantments.getOrThrow(net.minecraft.resources.ResourceKey.create(" +
                    "net.minecraft.core.registries.Registries.ENCHANTMENT, " +
                    "net.minecraft.resources.ResourceLocation.parse(\"example:reach\"))), " +
                    "enchantments.getOrThrow(net.minecraft.resources.ResourceKey.create(" +
                    "net.minecraft.core.registries.Registries.ENCHANTMENT, " +
                    "net.minecraft.resources.ResourceLocation.parse(\"minecraft:thorns\"))))) " +
                    ".build(HEX.location()));"
            ),
            enchantments
        )
        assertFalse(compact.contains("context.register(SHARPNESS_REF"), enchantments)

        val entries = read("example/data/ModEntriesProvider.java")
        assertTrue(
            entries.contains(
                "new RegistrySetBuilder()\n        .add(Registries.ENCHANTMENT, " +
                    "example.registry.ModEnchantments::bootstrap)\n        .add(Registries.DAMAGE_TYPE"
            ),
            entries
        )

        val tags = read("example/data/ModPorterEnchantmentTagsProvider.java")
        assertTrue(tags.contains("package example.data;"), tags)
        assertTrue(tags.contains("extends net.minecraft.data.tags.EnchantmentTagsProvider"), tags)
        assertTrue(tags.contains("super(output, lookupProvider, \"example\", existingFileHelper);"), tags)
        assertTrue(
            compact(tags).contains(
                "tag(net.minecraft.tags.EnchantmentTags.NON_TREASURE) .add(example.registry.ModEnchantments.REACH);"
            ),
            tags
        )
        listOf("CURSE", "TREASURE", "ON_RANDOM_LOOT", "TRADEABLE").forEach { tag ->
            assertTrue(
                compact(tags).contains("tag(net.minecraft.tags.EnchantmentTags.$tag) .add(example.registry.ModEnchantments.HEX);"),
                tags
            )
        }
        assertFalse(tags.contains("IN_ENCHANTING_TABLE"), tags)

        val datagen = read("example/data/ModDatagen.java")
        assertTrue(
            datagen.contains(
                "generator.addProvider(event.includeServer(), entries);\n" +
                    "        generator.addProvider(event.includeServer(), " +
                    "new ModPorterEnchantmentTagsProvider(output, lookupProvider, existingFileHelper));\n" +
                    "        generator.addProvider(event.includeServer(), new ModRecipes(output, lookupProvider));"
            ),
            datagen
        )

        val migrated = snapshot()
        assertTrue(migrate(dryRun = false).isEmpty())
        assertEquals(migrated, snapshot())
    }

    @Test
    fun `definitions with data driven effects are left to the static data`() {
        writeProject()
        generated(
            "example/enchantment/hex.json",
            hexDefinition.replace("\"weight\": 1", "\"weight\": 1,\n  \"effects\": {}")
        )
        val before = snapshot()

        assertTrue(migrate(dryRun = false).isEmpty())
        assertEquals(before, snapshot())
    }

    @Test
    fun `datagen graphs without one exact entries provider are left alone`() {
        writeProject()
        java(
            "example/data/SecondEntriesProvider.java",
            """
            package example.data;

            import java.util.Set;
            import java.util.concurrent.CompletableFuture;
            import net.minecraft.core.HolderLookup;
            import net.minecraft.core.RegistrySetBuilder;
            import net.minecraft.data.PackOutput;
            import net.neoforged.neoforge.common.data.DatapackBuiltinEntriesProvider;

            public class SecondEntriesProvider extends DatapackBuiltinEntriesProvider {
                private static final RegistrySetBuilder BUILDER = new RegistrySetBuilder();

                public SecondEntriesProvider(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
                    super(output, registries, BUILDER, Set.of("example"));
                }
            }
            """
        )
        val before = snapshot()

        assertTrue(migrate(dryRun = false).isEmpty())
        assertEquals(before, snapshot())
    }

    @Test
    fun `a look-alike entries provider is not a datagen bootstrap target`() {
        writeProject()
        java(
            "example/data/ModEntriesProvider.java",
            """
            package example.data;

            import java.util.Set;
            import java.util.concurrent.CompletableFuture;
            import net.minecraft.core.HolderLookup;
            import net.minecraft.core.RegistrySetBuilder;
            import net.minecraft.core.registries.Registries;
            import net.minecraft.data.PackOutput;

            public class ModEntriesProvider extends DatapackBuiltinEntriesProvider {
                private static final RegistrySetBuilder BUILDER = new RegistrySetBuilder()
                    .add(Registries.DAMAGE_TYPE, ModDamageTypes::bootstrap);

                public ModEntriesProvider(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
                    super(output, registries, BUILDER, Set.of("example"));
                }
            }

            class DatapackBuiltinEntriesProvider {
                DatapackBuiltinEntriesProvider(Object... arguments) {}
            }
            """
        )
        val before = snapshot()

        assertTrue(migrate(dryRun = false).isEmpty())
        assertEquals(before, snapshot())
    }

