    private fun writeProject() {
        java(
            "example/ExampleMod.java",
            """
            package example;

            public final class ExampleMod {
                public static final String ID = "example";
            }
            """
        )
        java(
            "example/registry/ModEnchantments.java",
            """
            package example.registry;

            import example.ExampleMod;
            import net.minecraft.world.item.enchantment.Enchantment;

            public class ModEnchantments {
                public static final net.minecraft.resources.ResourceKey<Enchantment> REACH =
                    net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ENCHANTMENT,
                        net.minecraft.resources.ResourceLocation.fromNamespaceAndPath("example", "reach"));

                public static final net.minecraft.resources.ResourceKey<Enchantment> HEX =
                    net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ENCHANTMENT,
                        net.minecraft.resources.ResourceLocation.fromNamespaceAndPath(ExampleMod.ID, "hex"));

                public static final net.minecraft.resources.ResourceKey<Enchantment> SHARPNESS_REF =
                    net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ENCHANTMENT,
                        net.minecraft.resources.ResourceLocation.fromNamespaceAndPath("minecraft", "sharpness"));

                public static final java.util.List<net.minecraft.resources.ResourceKey<Enchantment>> ENCHANTMENTS =
                    java.util.List.of(REACH, HEX);
            }
            """
        )
        java(
            "example/data/ModEntriesProvider.java",
            """
            package example.data;

            import java.util.Set;
            import java.util.concurrent.CompletableFuture;
            import example.ExampleMod;
            import net.minecraft.core.HolderLookup;
            import net.minecraft.core.RegistrySetBuilder;
            import net.minecraft.core.registries.Registries;
            import net.minecraft.data.PackOutput;
            import net.neoforged.neoforge.common.data.DatapackBuiltinEntriesProvider;

            public class ModEntriesProvider extends DatapackBuiltinEntriesProvider {
                private static final RegistrySetBuilder BUILDER = new RegistrySetBuilder()
                    .add(Registries.DAMAGE_TYPE, ModDamageTypes::bootstrap);

                public ModEntriesProvider(PackOutput output, CompletableFuture<HolderLookup.Provider> registries) {
                    super(output, registries, BUILDER, Set.of(ExampleMod.ID));
                }
            }
            """
        )
        java(
            "example/data/ModDatagen.java",
            """
            package example.data;

            import java.util.concurrent.CompletableFuture;
            import net.minecraft.core.HolderLookup;
            import net.minecraft.data.DataGenerator;
            import net.minecraft.data.PackOutput;
            import net.neoforged.neoforge.common.data.ExistingFileHelper;
            import net.neoforged.neoforge.data.event.GatherDataEvent;

            public class ModDatagen {
                public static void gather(GatherDataEvent event) {
                    DataGenerator generator = event.getGenerator();
                    PackOutput output = generator.getPackOutput();
                    CompletableFuture<HolderLookup.Provider> lookupProvider = event.getLookupProvider();
                    ExistingFileHelper existingFileHelper = event.getExistingFileHelper();
                    ModEntriesProvider entries = new ModEntriesProvider(output, lookupProvider);
                    lookupProvider = entries.getRegistryProvider();
                    generator.addProvider(event.includeServer(), entries);
                    generator.addProvider(event.includeServer(), new ModRecipes(output, lookupProvider));
                }
            }
            """
        )
        generated(
            "example/enchantment/reach.json",
            """
            {
              "anvil_cost": 4,
              "description": {
                "translate": "enchantment.example.reach"
              },
              "max_cost": {
                "base": 21,
                "per_level_above_first": 10
              },
              "max_level": 2,
              "min_cost": {
                "base": 1,
                "per_level_above_first": 10
              },
              "slots": [
                "mainhand"
              ],
              "supported_items": "#example:enchantable/reach",
              "weight": 2
            }
            """.trimIndent() + "\n"
        )
        generated("example/enchantment/hex.json", hexDefinition)
        generated(
            "example/tags/item/enchantable/reach.json",
            "{\n  \"values\": [\n    \"example:long_arm\",\n    \"example:longer_arm\"\n  ]\n}\n"
        )
        generated("minecraft/tags/enchantment/non_treasure.json", tag("example:reach"))
        generated("minecraft/tags/enchantment/curse.json", tag("example:hex"))
        generated("minecraft/tags/enchantment/treasure.json", tag("example:hex"))
        generated("minecraft/tags/enchantment/on_random_loot.json", tag("example:hex"))
        generated("minecraft/tags/enchantment/tradeable.json", tag("example:hex"))
    }

    private fun tag(vararg values: String): String =
        "{\n  \"values\": [\n" + values.joinToString(",\n") { "    \"$it\"" } + "\n  ]\n}\n"

    private fun migrate(dryRun: Boolean): List<Change> =
        LegacyEnchantmentDatagenBootstrap.migrate(StructuralRefactorPass(), directory, dryRun)

    private fun java(relative: String, source: String): Path {
        val file = directory.resolve("src/main/java").resolve(relative)
        file.parent.createDirectories()
        file.writeText(source.trimIndent() + "\n")
        return file
    }

    private fun generated(relative: String, content: String) {
        val file = directory.resolve("src/generated/resources/data").resolve(relative)
        file.parent.createDirectories()
        file.writeText(content)
    }

    private fun read(relative: String): String = directory.resolve("src/main/java").resolve(relative).readText()

    private fun snapshot(): Map<Path, String> = Files.walk(directory).use { stream ->
        stream.filter { Files.isRegularFile(it) }.sorted().toList()
    }.associateWith { it.readText() }

    private fun compact(source: String): String =
        source.replace(Regex("""\s+"""), " ")
            .replace(Regex("""\(\s+"""), "(")
            .replace(Regex("""\s+\)"""), ")")
            .trim()
}
